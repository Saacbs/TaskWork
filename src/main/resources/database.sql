CREATE TABLE IF NOT EXISTS SOLICITACAO (
 ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 NOME VARCHAR(160) NOT NULL, EMAIL VARCHAR(160) NOT NULL UNIQUE, TELEFONE VARCHAR(25),
 EMPRESA_ID INT NOT NULL REFERENCES EMPRESA(ID), PERFIL VARCHAR(20) NOT NULL,
 SENHA VARCHAR(255) NOT NULL, SITUACAO VARCHAR(20) DEFAULT 'Pendente' NOT NULL,
 CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS HISTORICO (
